const { chromium } = require('playwright');
const fs = require('fs'), path = require('path'), os = require('os');
const { createMock } = require('./mock');
const EXT = path.resolve(__dirname, '../udemy-toolkit');
const OUT = path.join(__dirname, 'shots'); fs.mkdirSync(OUT, { recursive: true });
const sleep = (ms) => new Promise(r => setTimeout(r, ms));
(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'uxk-'));
  const context = await chromium.launchPersistentContext(dir, { channel: 'chromium', headless: true, viewport: { width: 1400, height: 900 }, env: { ...process.env, LANG: 'C.UTF-8' }, args: [`--disable-extensions-except=${EXT}`, `--load-extension=${EXT}`, '--autoplay-policy=no-user-gesture-required', '--font-render-hinting=none'] });
  const mock = createMock();
  await context.route('https://www.udemy.com/**', mock.handle);
  await context.route('https://udemy-captions.s3.amazonaws.com/**', mock.handle);
  let [sw] = context.serviceWorkers(); if (!sw) sw = await context.waitForEvent('serviceworker');
  const extId = sw.url().split('/')[2];
  await sleep(500); for (const p of context.pages()) if (p.url().includes('options')) await p.close();
  const page = await context.newPage();
  await page.goto('https://www.udemy.com/home/my-courses/learning/');
  await page.waitForSelector('.uxk-card-badges', { timeout: 30000 });
  await page.screenshot({ path: path.join(OUT, '1-cards.png') });
  await page.click('#uxk-fab');
  await page.waitForSelector('.uxk-lib tbody tr');
  await page.locator('.uxk-lib tbody tr .uxk-sel').nth(1).check();
  await page.locator('.uxk-lib tbody tr .uxk-sel').nth(2).check();
  await page.screenshot({ path: path.join(OUT, '2-panel.png'), clip: { x: 220, y: 0, width: 1180, height: 900 } });
  mock.setCc('udemy'); // 실제 Udemy 구조를 본뜬 강의 화면 (영상 · 자막 띠 · 오른쪽 대본)
  await page.goto('https://www.udemy.com/course/test-course/learn/lecture/1001');
  await page.waitForFunction(() => document.querySelector('video').readyState >= 2);
  await page.mouse.click(300, 28);
  await page.keyboard.press('d'); await page.keyboard.press('d');
  await page.keyboard.press('v');
  await page.evaluate(() => { const v = document.querySelector('video'); v.pause(); v.currentTime = 2.5; });
  await page.waitForFunction(() => (document.querySelector('.uxk-sub1') || {}).textContent === 'Second sentence here', null, { timeout: 10000 });
  await page.waitForSelector('.uxk-capbox');
  await page.hover('#shaka-video-container');
  await sleep(400);
  await page.screenshot({ path: path.join(OUT, '3-player.png'), clip: { x: 8, y: 108, width: 968, height: 558 } }); // 영상 · 자막 · 도구 막대만
  await page.keyboard.press('h'); await sleep(300);
  await page.screenshot({ path: path.join(OUT, '4-help.png') });
  await page.keyboard.press('Escape');
  await page.click('.uxk-tb-subs', { force: true }); await page.waitForSelector('.uxk-modal select'); await sleep(300);
  await page.locator('.uxk-modal').screenshot({ path: path.join(OUT, '5-subsmenu.png') });
  await page.keyboard.press('Escape');
  const opt = await context.newPage();
  await opt.setViewportSize({ width: 1200, height: 1700 });
  await opt.goto(`chrome-extension://${extId}/pages/options.html`); await sleep(600);
  await opt.screenshot({ path: path.join(OUT, '6-options.png'), clip: { x: 0, y: 0, width: 1200, height: 900 } });
  const pop = await context.newPage();
  await pop.setViewportSize({ width: 360, height: 520 });
  await pop.goto(`chrome-extension://${extId}/pages/popup.html`); await sleep(500);
  await pop.screenshot({ path: path.join(OUT, '7-popup.png') });
  await context.close();
  console.log('ok');
})();
